function ensureDir(folderPath) {
	fs.mkdirSync(path.join(ROOT, folderPath), { recursive: true });
}

function ensureGitkeep(folderPath) {
	ensureDir(folderPath);
	const gitkeep = path.join(ROOT, folderPath, '.gitkeep');
	if (!fs.existsSync(gitkeep)) {
		fs.writeFileSync(gitkeep, '');
	}
}

function readJsonIfExists(filePath) {
	const fullPath = path.join(ROOT, filePath);
	if (!fs.existsSync(fullPath)) return {};
	try {
		return JSON.parse(fs.readFileSync(fullPath, 'utf8'));
	} catch (error) {
		return {
			_json_parse_error: String(error.message || error),
			_previous_file_unreadable: true,
		};
	}
}

function writeJsonMerged(filePath, nextFields) {
	const fullPath = path.join(ROOT, filePath);
	ensureDir(path.dirname(filePath));

	const existing = readJsonIfExists(filePath);
	const merged = {
		...existing,
		...nextFields,
		_last_scaffold_sync: new Date().toISOString(),
	};

	fs.writeFileSync(fullPath, JSON.stringify(merged, null, 2) + '\n');
}

function listLectureLikeDirs(topicFolder) {
	const fullTopicPath = path.join(ROOT, topicFolder);
	if (!fs.existsSync(fullTopicPath)) return [];
	return fs
		.readdirSync(fullTopicPath, { withFileTypes: true })
		.filter(entry => entry.isDirectory())
		.map(entry => entry.name)
		.filter(name => /^lecture-\d+/.test(name))
		.map(name => `${topicFolder}/${name}`);
}

